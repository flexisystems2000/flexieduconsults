<script type="module">
  import { initializeApp } from "https://www.gstatic.com/firebasejs/9.22.0/firebase-app.js";
  import { getFirestore, collection, onSnapshot, query, orderBy, doc, increment, updateDoc, addDoc, serverTimestamp, getDoc, setDoc, deleteDoc } from "https://www.gstatic.com/firebasejs/9.22.0/firebase-firestore.js";
  import { getAuth } from "https://www.gstatic.com/firebasejs/9.22.0/firebase-auth.js";

  // Disable copy/paste and selection behaviors programmatically
  document.addEventListener('copy', (e) => e.preventDefault());
  document.addEventListener('cut', (e) => e.preventDefault());
  document.addEventListener('paste', (e) => e.preventDefault());

  const firebaseConfig = {
    apiKey: "AIzaSyA0bM6pk1T1peGSS7quvFPEMOMuplnNRNM",
    authDomain: "auth.flexieduconsult.com.ng",
    projectId: "waec2026jamb2027"
  };

  const app = initializeApp(firebaseConfig);
  const db = getFirestore(app);
  const auth = getAuth(app);

  let selectedVideo = null;
  let allVideos = [];
  let userInteractions = {};
  let activeVideoUnsub = null;

  window.postComment = async (id) => {
    if (!auth.currentUser) {
        alert("Sign in to comment!");
        window.location.href = `login.php?redirect=${encodeURIComponent(window.location.href)}`;
        return;
    }

    const commentInput = document.getElementById(`input-${id}`);
    const commentText = commentInput.value;

    if (commentText.trim() === "") return;

    try {
        await addDoc(collection(db, "videos", id, "comments"), {
            text: commentText,
            userId: auth.currentUser.uid,
            userName: auth.currentUser.displayName || "Anonymous",
            createdAt: serverTimestamp()
        });

        commentInput.value = "";
        alert("Comment posted!");
    } catch (e) {
        console.error("Error adding comment: ", e);
        alert("Failed to post comment. Please try again.");
    }
  };

  window.toggleInteraction = async (type) => {
    if (!auth.currentUser) {
        alert("Sign in to react!");
        window.location.href = `login.php?redirect=${encodeURIComponent(window.location.href)}`;
        return;
    }
    const userId = auth.currentUser.uid;
    const videoId = selectedVideo.id;
    const interactionRef = doc(db, "interactions", `${videoId}_${userId}`);
    const videoRef = doc(db, "videos", videoId);
    const docSnap = await getDoc(interactionRef);

    if (docSnap.exists() && docSnap.data().type === type) {
        await deleteDoc(interactionRef);
        await updateDoc(videoRef, { [type]: increment(-1) });
    } else {
        if (docSnap.exists()) await updateDoc(videoRef, { [docSnap.data().type]: increment(-1) });
        await setDoc(interactionRef, { userId, videoId, type });
        await updateDoc(videoRef, { [type]: increment(1) });
    }
  };

  window.reactToComment = async (commentId, type) => {
    if (!auth.currentUser) {
        alert("Sign in to react!");
        return;
    }

    const videoId = selectedVideo.id;
    const commentRef = doc(db, "videos", videoId, "comments", commentId);
    const interactionRef = doc(db, "videos", videoId, "comments", commentId, "interactions", auth.currentUser.uid);

    try {
        const snap = await getDoc(interactionRef);

        if (snap.exists()) {
            if (snap.data().type === type) {
                await deleteDoc(interactionRef);
                await updateDoc(commentRef, { [type]: increment(-1) });
            } else {
                const oldType = snap.data().type;
                await updateDoc(commentRef, { [oldType]: increment(-1) });
                await setDoc(interactionRef, { type: type });
                await updateDoc(commentRef, { [type]: increment(1) });
            }
        } else {
            await setDoc(interactionRef, { type: type });
            await updateDoc(commentRef, { [type]: increment(1) });
        }
    } catch (e) {
        console.error("Error reacting: ", e);
    }
  };

  window.showReplyBox = (idWithSuffix) => {
    const targetBox = document.getElementById(`reply-box-${idWithSuffix}`);
    if (targetBox) {
        const isHidden = targetBox.style.display === "none";
        targetBox.style.display = isHidden ? "flex" : "none";
    }
  };

  window.postReply = async (commentId, suffix = "") => {
    if (!auth.currentUser) {
        alert("Sign in to reply!");
        window.location.href = `login.php?redirect=${encodeURIComponent(window.location.href)}`;
        return;
    }
    const input = document.getElementById(`reply-input-${commentId}${suffix}`);
    const text = input.value;
    if (!text.trim()) return;

    try {
        const videoId = selectedVideo.id;
        await addDoc(collection(db, "videos", videoId, "comments", commentId, "replies"), {
            text: text,
            userName: auth.currentUser.displayName || "Anonymous",
            createdAt: serverTimestamp()
        });

        await updateDoc(doc(db, "videos", videoId, "comments", commentId), {
            replyCount: increment(1)
        });

        input.value = "";
        document.getElementById(`reply-box-${commentId}${suffix}`).style.display = "none";
        alert("Reply posted!");
    } catch (e) {
        console.error("Error posting reply: ", e);
    }
  };

  window.toggleReplies = (commentId, suffix = "") => {
    const list = document.getElementById(`replies-list-${commentId}${suffix}`);
    if (list.style.display === "none") {
        list.style.display = "block";
        const videoId = selectedVideo.id;
        onSnapshot(query(collection(db, "videos", videoId, "comments", commentId, "replies"), orderBy("createdAt", "asc")), (snap) => {
            list.innerHTML = "";
            snap.forEach(r => {
                const rData = r.data();
                list.innerHTML += `<div style="margin-bottom:5px;"><strong style="font-size:11px;">${rData.userName}:</strong> <span style="font-size:12px;">${rData.text}</span></div>`;
            });
        });
    } else {
        list.style.display = "none";
    }
  };

  window.openCommentsModal = (videoId) => {
    const modal = document.getElementById('comments-modal');
    modal.style.setProperty('display', 'flex', 'important');
    const list = document.getElementById('modal-comments-list');
    list.innerHTML = "<h4>All Comments</h4>";

    onSnapshot(query(collection(db, "videos", videoId, "comments"), orderBy("createdAt", "desc")), (snap) => {
        list.innerHTML = "<h4>All Comments</h4>";
        snap.forEach(docSnap => {
            renderComment(docSnap, list);
        });
    });
  };

  window.postModalComment = async () => {
    const input = document.getElementById('input-modal');
    if (!input || !input.value.trim()) return;

    if (selectedVideo) {
        const mainInput = document.getElementById(`input-${selectedVideo.id}`);
        if (mainInput) {
            mainInput.value = input.value;
            await postComment(selectedVideo.id);
            input.value = "";
        }
    }
  };

  window.closeModal = () => {
    document.getElementById('comments-modal').style.display = 'none';
  };

  const renderComment = (docSnap, container) => {
    const data = docSnap.data();
    const div = document.createElement('div');
    div.style = "background: #f1f5f9; padding: 12px; border-radius: 12px; margin-top: 10px;";

    const isModal = container.id === 'modal-comments-list';
    const suffix = isModal ? '-modal' : '';

    div.innerHTML = `
        <div style="font-weight: bold; font-size: 13px;">${data.userName || "Anonymous"}</div>
        <div style="font-size: 14px; margin: 4px 0;">${data.text}</div>
        <div style="font-size: 12px; display: flex; gap: 15px; color: #475569; font-weight: 600; flex-wrap: wrap;">
            <span style="cursor:pointer;" onclick="reactToComment('${docSnap.id}', 'likes')">Like (${data.likes || 0})</span>
            <span style="cursor:pointer;" onclick="reactToComment('${docSnap.id}', 'dislikes')">Dislike (${data.dislikes || 0})</span>
            <span style="cursor:pointer; color:#1e3a8a;" onclick="showReplyBox('${docSnap.id}${suffix}')">Reply</span>
            <span style="cursor:pointer; color:#475569;" onclick="toggleReplies('${docSnap.id}', '${suffix}')">View Replies (${data.replyCount || 0})</span>
        </div>
        <div id="reply-box-${docSnap.id}${suffix}" style="display:none; margin-top:10px; background:white; padding:5px; border-radius:20px; border:1px solid #d1d5db; align-items:center; width: 100%; box-sizing: border-box;">
            <input type="text" id="reply-input-${docSnap.id}${suffix}" placeholder="Reply..." style="flex-grow:1; border:none; padding:8px 12px; outline:none; background:transparent; font-size:13px; width: 60%;">
            <button onclick="postReply('${docSnap.id}', '${suffix}')" style="background:#003366; color:white; border:none; padding:6px 15px; border-radius:20px; cursor:pointer; font-size:11px; font-weight:bold;">Send</button>
        </div>
        <div id="replies-list-${docSnap.id}${suffix}" style="display:none; margin-top:10px; margin-left:20px; border-left:2px solid #cbd5e1; padding-left:10px;"></div>
    `;
    container.appendChild(div);
  };

  window.loadComments = (videoId) => {
    const list = document.getElementById('comments-list');
    if (!list) return;

    onSnapshot(query(collection(db, "videos", videoId, "comments"), orderBy("createdAt", "desc")), (snap) => {
        list.innerHTML = "<h4>Comments</h4>";
        const docs = snap.docs;

        docs.slice(0, 3).forEach(docSnap => {
            renderComment(docSnap, list);
        });

        if (docs.length > 3) {
            list.innerHTML += `
                <div style="cursor:pointer; color:#1e3a8a; font-weight:bold; margin-top:10px; font-size:14px;"
                     onclick="openCommentsModal('${videoId}')">
                     View more comments (${docs.length})
                </div>`;
        }
    });
  };

  const updateCounts = (vData, userChoice) => {
    const likesEl = document.getElementById('likes-count');
    const dislikesEl = document.getElementById('dislikes-count');
    const subsEl = document.getElementById('subs-count');

    if (likesEl) {
        likesEl.innerText = vData.likes || 0;
        likesEl.parentElement.style.color = userChoice === 'likes' ? '#1e3a8a' : 'inherit';
    }
    if (dislikesEl) {
        dislikesEl.innerText = vData.dislikes || 0;
        dislikesEl.parentElement.style.color = userChoice === 'dislikes' ? '#e11d48' : 'inherit';
    }
    if (subsEl) {
        subsEl.innerText = vData.subs || 0;
        subsEl.parentElement.style.color = userChoice === 'subs' ? '#22c55e' : 'inherit';
    }
  };

  const listenToVideoUpdates = (videoId) => {
    return onSnapshot(doc(db, "videos", videoId), (docSnap) => {
        if (docSnap.exists()) {
            const data = docSnap.data();
            const index = allVideos.findIndex(v => v.id === videoId);
            if (index !== -1) {
                allVideos[index] = { id: videoId, data: () => data };
            }
            updateCounts(data, userInteractions[videoId]);
        }
    });
  };

  const render = () => {
    const container = document.getElementById('mainVideoContainer');
    if (!selectedVideo) return;

    const isSameVideo = container.dataset.videoId === selectedVideo.id;
    if (isSameVideo) {
        updateCounts(selectedVideo.data(), userInteractions[selectedVideo.id]);
        return;
    }

    if (activeVideoUnsub) activeVideoUnsub();
    activeVideoUnsub = listenToVideoUpdates(selectedVideo.id);

    const v = selectedVideo.data();
    const id = v.link.includes("v=") ? v.link.split("v=")[1].split("&")[0] : v.link.split("/").pop();
    const others = allVideos.filter(d => d.id !== selectedVideo.id);
    const userChoice = userInteractions[selectedVideo.id];

    container.dataset.videoId = selectedVideo.id;

    container.innerHTML = `
      <div class="card">
        <iframe src="https://www.youtube.com/embed/${id}" width="100%" height="315" allowfullscreen title="${v.title || 'Video'}"></iframe>
        <h3>${v.title}</h3>
        <p>${v.desc || ''}</p>

        <div class="actions">
          <div class="btn-icon" style="color: ${userChoice === 'likes' ? '#1e3a8a' : 'inherit'};" onclick="toggleInteraction('likes')">
            <svg viewBox="0 0 24 24" width="20" height="20" fill="none" stroke="currentColor" stroke-width="2"><path d="M14 9V5a3 3 0 00-3-3l-4 9v11h11.28a2 2 0 002-1.7l1.38-9a2 2 0 00-2-2.3zM7 9H4v12h3M7 9V5"></path></svg>
            <span id="likes-count">${v.likes || 0}</span>
